ALTER TABLE produtos
    ADD COLUMN IF NOT EXISTS disponivel BOOLEAN NOT NULL DEFAULT TRUE;

-- Sincroniza registros antigos: saldo zerado = indisponível
UPDATE produtos SET disponivel = FALSE WHERE estoque <= 0 AND disponivel;

-- 2. Auditoria (Kardex) — evento_id UNIQUE garante a idempotência
CREATE TABLE IF NOT EXISTS movimentacoes_estoque (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id      UUID NOT NULL UNIQUE,
    produto_id     BIGINT NOT NULL REFERENCES produtos(id),
    tipo           VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA','SAIDA')),
    quantidade     INTEGER NOT NULL CHECK (quantidade > 0),
    saldo_anterior INTEGER NOT NULL,
    saldo_atual    INTEGER NOT NULL,
    criado_em      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Alertas de reposição (Compras)
CREATE TABLE IF NOT EXISTS alertas_reposicao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id     BIGINT NOT NULL REFERENCES produtos(id),
    saldo_atual    INTEGER NOT NULL,
    estoque_minimo INTEGER NOT NULL,
    status         VARCHAR(10) NOT NULL DEFAULT 'PENDENTE'
                   CHECK (status IN ('PENDENTE','RESOLVIDO')),
    criado_em      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. RLS + políticas (mesmo padrão da tabela produtos)
ALTER TABLE movimentacoes_estoque ENABLE ROW LEVEL SECURITY;
ALTER TABLE alertas_reposicao ENABLE ROW LEVEL SECURITY;

